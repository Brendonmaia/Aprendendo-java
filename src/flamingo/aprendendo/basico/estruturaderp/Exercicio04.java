public class Exercicio04 {
    static void main() {
            int soma = 0; // Variável acumuladora

            for (int i = 1; i <= 100; i++) {
                soma += i; // Acumula o valor de i na variável soma
            }

            System.out.println("A soma de 1 até 100 é: " + soma);
        }
    }

