package flamingo.aprendendo.basico;

public class OperadoresParte06 {
    public static void main(String[] args) {
        //Incremento e Decremento

        int contador = 0;
        contador = contador +1; // 1
        contador +=1; //2
        contador ++; //3

        contador = contador -1; //2
        contador = -1; //1
        contador--; // 0

        System.out.println("contador");
    }
}
